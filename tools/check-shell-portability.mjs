#!/usr/bin/env node

/**
 * Validate shell scripts for cross-platform portability (Linux distros + macOS,
 * bash 3.2 baseline). Complements check-module-bin.mjs.
 *
 * Usage:
 *   node tools/check-shell-portability.mjs --root <dir> [--root <dir2> ...]
 *                                          [--no-bash-n] [--exclude dir,dir]
 *
 * Rules
 *  - BASH4:    bash 4+ syntax (assoc arrays, declare -g, mapfile, ${var,,}, ...)
 *  - GNU-ONLY: GNU coreutils/grep/sed specific flags that BSD/macOS lack
 *              (stat -c, sha256sum, sed -i, base64 -w, xargs -r, ...)
 *
 * A line is exempt when it (or a comment line up to 2 lines above it) carries
 * one of two markers:
 *  - `PORTABILITY:target-linux` — the code only ever executes on a GNU/Linux
 *    target host (e.g. remote scripts generated by sdkwork_remote, postgres
 *    container init).
 *  - `PORTABILITY:allow` — the flagged token is intentional on the operator
 *    machine, e.g. a portable shim that probes tool availability first
 *    (command -v sha256sum || shasum || openssl).
 *
 * Pure comment lines are never flagged (documentation may name the tokens).
 *
 * bash -n is executed for every file when a bash binary is reachable; pass
 * --no-bash-n to skip (e.g. on hosts without bash).
 */

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { parseArgs } from 'node:util';

const MARKERS = Object.freeze(['PORTABILITY:target-linux', 'PORTABILITY:allow']);
const MARKER_WINDOW = 2; // a marker comment up to 2 lines above also exempts the line

// bash 4+ syntax that macOS /usr/bin/bash (3.2) cannot parse or run.
const BASH4_RULES = Object.freeze([
  { pattern: /\b(declare|local|typeset|export)\s+(-[a-zA-Z]*A)/, issue: 'associative array (bash 4+); use parallel indexed arrays + a lookup function' },
  { pattern: /\bdeclare\s+-g/, issue: 'declare -g (bash 4.2+); declare globals at file scope' },
  { pattern: /\b(mapfile|readarray)\b/, issue: 'mapfile/readarray (bash 4+); use a while IFS= read -r loop' },
  { pattern: /\$\{[^}]*,(,)\}/, issue: '${var,,} lowercase expansion (bash 4+); use tr' },
  { pattern: /\$\{[^}]*\^\^\}/, issue: '${var^^} uppercase expansion (bash 4+); use tr' },
  { pattern: /\bcoproc\b/, issue: 'coproc (bash 4+)' },
  { pattern: /\|&/, issue: '|& pipe to stderr (bash 4+); use 2>&1 |' },
  { pattern: /;;&/, issue: ';;& case fallthrough (bash 4+); use explicit fallthrough logic' },
  { pattern: /printf\s+['"][^'"]*%\([^)]*\)T/, issue: "printf %(...)T (bash 4.2+); use date -u" },
  { pattern: /\[(-\d+)/, issue: 'negative array subscript (bash 4.3+)' },
  { pattern: /\$\{![A-Za-z_][A-Za-z0-9_]*[@*]\}/, issue: '${!prefix@} name expansion (bash 4.3+); iterate keys explicitly' },
]);

// GNU-only command usage that BSD/macOS coreutils reject or answer differently.
const GNU_RULES = Object.freeze([
  { pattern: /\bstat\s+(-[a-zA-Z]*c|--format)/, issue: 'stat -c (GNU); use sdkwork_file_mtime (stat -c/-f shim)' },
  { pattern: /\bsha256sum\b/, issue: 'sha256sum (GNU coreutils); use sdkwork_sha256_file or the sha256sum/shasum/openssl chain' },
  { pattern: /\bsed\s+[^|;&\n]*\B-i/, issue: 'sed -i (BSD needs -i \'\', GNU breaks on it); use awk + tmp + mv' },
  { pattern: /\bbase64\s+(-[a-zA-Z]*w)/, issue: 'base64 -w (GNU); base64 | tr -d \'\\r\\n\' fallback exists in sdkwork-common.sh' },
  { pattern: /\bxargs\s+[^|;&\n]*-r\b/, issue: 'xargs -r (GNU); guard with a count check instead' },
  { pattern: /\btimeout\s+-?\d/, issue: 'timeout N (GNU coreutils); not present on macOS' },
  { pattern: /\breadlink\s+[^|;&\n]*-f/, issue: 'readlink -f (GNU); not on macOS bash env' },
  { pattern: /\bdate\s+(-d|--date)/, issue: 'date -d (GNU); use UTC epoch math or date -u' },
  { pattern: /\bgetent\b/, issue: 'getent (glibc); not on macOS/BSD' },
  { pattern: /\bsort\s+-h\b/, issue: 'sort -h (GNU); not on BSD sort' },
  { pattern: /\bdu\s+-[a-zA-Z]*b/, issue: 'du -b (GNU); use du -k on both platforms' },
  { pattern: /\btruncate\s/, issue: 'truncate (GNU coreutils); not on macOS' },
  { pattern: /\brealpath\b/, issue: 'realpath (not on macOS pre-13); use cd + pwd' },
  { pattern: /\bgrep\s+(-[a-zA-Z]*P)/, issue: 'grep -P (PCRE, GNU-only); use grep -E' },
  { pattern: /\binstall\s+(-[a-zA-Z]*D)/, issue: 'install -D (GNU); mkdir -p then install' },
]);

const DEFAULT_EXCLUDES = Object.freeze(['node_modules', '.git', 'target']);

function walkShFiles(dir, excludes, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (excludes.has(entry.name)) continue;
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walkShFiles(p, excludes, out);
    else if (entry.isFile() && entry.name.endsWith('.sh')) out.push(p);
  }
  return out;
}

function isExempt(lines, idx) {
  for (let back = 0; back <= MARKER_WINDOW; back += 1) {
    const i = idx - back;
    if (i < 0) break;
    if (MARKERS.some((m) => lines[i].includes(m))) return true;
  }
  return false;
}

function lintFile(file) {
  const findings = [];
  const lines = fs.readFileSync(file, 'utf8').split('\n');
  lines.forEach((line, idx) => {
    if (/^\s*#/.test(line)) return; // comment lines are documentation, not code
    if (isExempt(lines, idx)) return;
    for (const { pattern, issue } of BASH4_RULES) {
      if (pattern.test(line)) {
        findings.push(`${file}:${idx + 1}: BASH4: ${issue}: ${line.trim().slice(0, 120)}`);
      }
    }
    for (const { pattern, issue } of GNU_RULES) {
      if (pattern.test(line)) {
        findings.push(`${file}:${idx + 1}: GNU-ONLY: ${issue}: ${line.trim().slice(0, 120)}`);
      }
    }
  });
  return findings;
}

function bashSyntaxCheck(file) {
  try {
    execFileSync('bash', ['-n', file], { stdio: 'pipe' });
    return [];
  } catch (err) {
    const detail = (err.stderr && err.stderr.toString().trim()) || err.message;
    return [`${file}: bash -n failed: ${detail}`];
  }
}

function main() {
  const { values } = parseArgs({
    options: {
      help: { type: 'boolean', short: 'h' },
      root: { type: 'string', multiple: true, default: [] },
      exclude: { type: 'string', default: '' },
      'bash-n': { type: 'boolean', default: true },
    },
  });
  if (values.help || values.root.length === 0) {
    console.log('Usage: node tools/check-shell-portability.mjs --root <dir> [--root <dir2> ...] [--no-bash-n] [--exclude dir,dir]');
    return;
  }

  const excludes = new Set([...DEFAULT_EXCLUDES, ...values.exclude.split(',').filter(Boolean)]);
  const findings = [];
  let fileCount = 0;
  let bashAvailable = true;
  if (values['bash-n']) {
    try { execFileSync('bash', ['-n', '/dev/null'], { stdio: 'pipe' }); }
    catch { bashAvailable = false; }
  }

  for (const root of values.root) {
    const abs = path.resolve(root);
    if (!fs.existsSync(abs)) {
      findings.push(`${abs}: root does not exist`);
      continue;
    }
    for (const file of walkShFiles(abs, excludes)) {
      fileCount += 1;
      findings.push(...lintFile(file));
      if (values['bash-n'] && bashAvailable) findings.push(...bashSyntaxCheck(file));
    }
  }

  if (findings.length > 0) {
    console.error(`shell portability failed (${findings.length} findings across ${fileCount} files)`);
    findings.forEach((f) => console.error(`- ${f}`));
    process.exitCode = 1;
    return;
  }
  console.log(`shell portability passed: ${fileCount} files, 0 findings (bash -n: ${values['bash-n'] && bashAvailable ? 'on' : 'off'})`);
}

main();
